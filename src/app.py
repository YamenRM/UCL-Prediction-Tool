"""
UCL Prediction Tool — Streamlit app.

Reads pre-computed predictions from models/predictions_2627.csv (produced
by src/predict.py) and the trained model's metadata from models/rf_final.pkl.
No live inference happens in the app itself — predictions are generated by
the pipeline (scheduled weekly via GitHub Actions) and this app just
presents them.

Run locally by:
    streamlit run src/App.py
"""

import pickle
import pandas as pd
import streamlit as st
from Configuration import MODELS_DIR, PREDICTIONS_OUTPUT_PATH, PRODUCTION_MODEL_PATH 


PRODUCTION_MODEL_PATH = f"{MODELS_DIR}/rf_final.pkl"
PREDICTIONS_OUTPUT_PATH = f"{MODELS_DIR}/predictions_2627.csv"

BIG5_LEAGUES = ["ENG-Premier League", "ESP-La Liga", "FRA-Ligue 1", "GER-Bundesliga", "ITA-Serie A"]
UCL_LEAGUE = "INT-Champions League"


EVAL_METRICS = {
    "accuracy": 0.5159,
    "naive_baseline_accuracy": 0.4460,
    "log_loss": 0.9909,
}


@st.cache_data
def load_predictions() -> pd.DataFrame:
    df = pd.read_csv(PREDICTIONS_OUTPUT_PATH, parse_dates=["date"])
    return df


@st.cache_resource
def load_model_bundle():
    with open(PRODUCTION_MODEL_PATH, "rb") as f:
        return pickle.load(f)


# checks if a row has any missing data flags (Elo or squad rating) and returns True/Falses
def has_missing_data(row: pd.Series) -> bool:
    flag_cols = ["home_elo_missing", "away_elo_missing",
                 "home_squad_rating_missing", "away_squad_rating_missing"]
    present = [c for c in flag_cols if c in row.index]
    if not present:
        return False
    return bool(row[present].any())


st.set_page_config(page_title="UCL Prediction Tool", page_icon="⚽", layout="wide")

st.title("⚽ UCL Prediction Tool")
st.caption(
    "Match outcome predictions (Home / Draw / Away) for the 2026/27 UEFA Champions League "
    "and Big-5 European leagues, from a Random Forest model trained on Elo ratings, squad "
    "strength, form, and rest days."
)

# data loading
try:
    predictions = load_predictions()
except FileNotFoundError:
    st.error(
        f"No predictions file found at `{PREDICTIONS_OUTPUT_PATH}`. "
        "Run the pipeline (`src/predict.py`) first to generate predictions."
    )
    st.stop()

try:
    model_bundle = load_model_bundle()
    model_available = True
except FileNotFoundError:
    model_bundle = None
    model_available = False

# sidebar filters
st.sidebar.header("Filters")

league_options = ["All"] + sorted(predictions["league"].unique().tolist())
selected_league = st.sidebar.selectbox("League", league_options)

team_search = st.sidebar.text_input("Search team", placeholder="e.g. Barcelona")

min_date = predictions["date"].min().date()
max_date = predictions["date"].max().date()
date_range = st.sidebar.slider(
    "Date range",
    min_value=min_date, max_value=max_date,
    value=(min_date, max_date),
)

hide_low_confidence = st.sidebar.checkbox(
    "Hide fixtures with imputed team data",
    value=False,
    help="Hides fixtures where either team is missing real Elo or squad-rating "
         "data (common for lower-tier clubs in early UCL qualifying rounds), "
         "since those predictions are less reliable.",
)

# filtering logic
filtered = predictions.copy()

if selected_league != "All":
    filtered = filtered[filtered["league"] == selected_league]

if team_search:
    mask = (
        filtered["home_team"].str.contains(team_search, case=False, na=False)
        | filtered["away_team"].str.contains(team_search, case=False, na=False)
    )
    filtered = filtered[mask]

filtered = filtered[
    (filtered["date"].dt.date >= date_range[0]) & (filtered["date"].dt.date <= date_range[1])
]

filtered["low_confidence"] = filtered.apply(has_missing_data, axis=1)
if hide_low_confidence:
    filtered = filtered[~filtered["low_confidence"]]

filtered = filtered.sort_values("date")

#metrics panel
col1, col2, col3 = st.columns(3)
col1.metric("Fixtures shown", len(filtered))
col2.metric("Model accuracy (held-out 2025/26)", f"{EVAL_METRICS['accuracy']:.1%}",
            delta=f"+{(EVAL_METRICS['accuracy'] - EVAL_METRICS['naive_baseline_accuracy']) * 100:.1f} pts vs naive")
col3.metric("Log loss (held-out 2025/26)", f"{EVAL_METRICS['log_loss']:.3f}")

st.divider()

# display fixtures
if filtered.empty:
    st.info("No fixtures match the current filters.")
else:
    for _, row in filtered.iterrows():
        with st.container(border=True):
            header_col, badge_col = st.columns([5, 1])

            with header_col:
                st.markdown(f"**{row['home_team']}** vs **{row['away_team']}**")
                st.caption(f"{row['league']}  ·  {row['date'].strftime('%b %d, %Y')}")

            with badge_col:
                if row["low_confidence"]:
                    st.markdown("⚠️ :orange[Limited data]")

            prob_h = row.get("prob_H", 0.0)
            prob_d = row.get("prob_D", 0.0)
            prob_a = row.get("prob_A", 0.0)

            bar_col1, bar_col2, bar_col3 = st.columns(3)
            bar_col1.metric("Home win", f"{prob_h:.0%}")
            bar_col2.metric("Draw", f"{prob_d:.0%}")
            bar_col3.metric("Away win", f"{prob_a:.0%}")

            st.progress(float(prob_h), text=None)

# explanation panel
with st.expander("📊 About the model"):
    st.markdown(
        """
        **Model**: Random Forest classifier, tuned via randomized hyperparameter search.

        **Training data**: 9,672 matches across the Big-5 European leagues and UEFA
        Champions League, 2021/22 through 2025/26 seasons, with exponential recency
        weighting (recent matches weighted up to ~7x more than 2021/22 matches).

        **Evaluation**: metrics above come from a model deliberately trained without
        the 2025/26 season, then evaluated on those genuinely unseen matches — not
        the production model used for live predictions, to avoid inflated results.
        """
    )

    if model_available and model_bundle is not None:
        st.markdown("**Top predictive features**")
        model = model_bundle["model"]
        feature_cols = model_bundle["feature_cols"]
        importances = (
            pd.Series(model.feature_importances_, index=feature_cols)
            .sort_values(ascending=False)
            .head(10)
        )
        st.bar_chart(importances)

        st.caption(
            f"Production model trained on seasons: {model_bundle.get('trained_on_seasons', 'unknown')} "
            f"({model_bundle.get('trained_on_rows', '?')} matches)"
        )
    else:
        st.caption("Model file not found — feature importance chart unavailable.")

st.divider()
st.caption(
    "⚠️ Predictions are a statistical estimate based on historical data, Elo ratings, and "
    "squad strength proxies — not a guarantee of outcomes. Fixtures flagged 'Limited data' "
    "involve at least one team with imputed (not directly measured) Elo or squad-rating data, "
    "typically smaller clubs in early UCL qualifying rounds."
)
